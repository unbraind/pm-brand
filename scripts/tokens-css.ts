/** Derive the public stylesheet from the canonical TypeScript values, retaining theme/motion selectors. */
import { readFileSync, writeFileSync } from 'node:fs';
import { tokens } from '../src/tokens.ts';
/** Serialize every contract suffix as a CSS declaration. */
function declarations(theme: 'light' | 'dark', indent: string): string {
  return Object.entries(tokens[theme]).map(([name, value]) => `${indent}--pm-${name}: ${value};`).join('\n');
}
const css = `/* Generated by scripts/tokens-css.ts from src/tokens.ts. See CONTRACT.md. */
:root {
${declarations('light', '  ')}
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${declarations('dark', '    ')}
    color-scheme: dark;
  }
}

:root[data-theme="dark"] {
${declarations('dark', '  ')}
  color-scheme: dark;
}

@media (prefers-reduced-motion: reduce) {
  :root { --pm-dur: 0s; }
}
`;
if (process.argv.includes('--check')) {
  if (readFileSync('tokens.css', 'utf8') !== css) throw new Error('Stale tokens.css; run npm run tokens:build');
  console.log('Canonical TypeScript and generated CSS tokens agree');
} else writeFileSync('tokens.css', css);
